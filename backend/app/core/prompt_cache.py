class PromptCacheManager:
    def __init__(self, max_entries: int = 512) -> None:
        self._max_entries = max(1, max_entries)
        self._cache: OrderedDict[str, str] = OrderedDict()

    def build_text_system_prompt(
        self,
        *,
        profile_text: str = "",
        memory_text: str = "",
        workspace_instructions: str = "",
    ) -> str:
        return self._join(
            self._base_prompt(),
            self._cached_section(
                "workspace",
                "Инструкции рабочего пространства (применяй, если они не конфликтуют с системными правилами выше)",
                workspace_instructions,
            ),
            self._cached_section("profile", "Профиль пользователя", profile_text),
            self._static_prompt(
                "text:profile-guidance:v1",
                [
                    "Если вопрос относится к самому пользователю, сначала опирайся на профиль пользователя, если в текущем запросе нет явного исправления этих данных.",
                    "Если пользователь в текущем сообщении исправляет своё имя, роль или предпочтения, считай это более свежим источником истины, чем профиль.",
                ],
            ),
            self._static_prompt(
                "text:completion-guidance:v1",
                [
                    "Требование к качеству ответа:",
                    "- Цель ответа — полностью закрыть задачу пользователя, а не дать поверхностный обзор.",
                    "- Если запрос состоит из нескольких частей, покрой каждую существенную часть явно.",
                    "- Для анализа, сравнения, рекомендаций, планов и разборов доводи ответ до законченного состояния: итог, ключевые основания, ограничения/риски и практический следующий шаг, если это уместно.",
                    "- Сначала давай прямой ответ или вывод, затем детали и пояснения.",
                    "- Если нужно сделать разумное предположение из неполных данных, коротко помечай его как предположение и не выдавай за подтвержденный факт.",
                ],
            ),
            self._section("Релевантные воспоминания (используй только если они помогают текущему запросу)", memory_text),
        )

